/// Tiny translation layer: English strings are the keys, French (and any
/// later language) overrides them. `tr()` falls back to the key, so an
/// untranslated string still reads correctly in English.
enum AppLanguage {
  en('English', 'en', '🇬🇧'),
  fr('Français', 'fr', '🇫🇷');

  const AppLanguage(this.label, this.code, this.flag);
  final String label;
  final String code;
  final String flag;
}

AppLanguage currentLanguage = AppLanguage.en;

String tr(String en) {
  if (currentLanguage == AppLanguage.en) return en;
  return _fr[en] ?? en;
}

const List<String> _monthsEn = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const List<String> _monthsFr = ['janvier', 'février', 'mars', 'avril', 'mai', 'juin', 'juillet', 'août', 'septembre', 'octobre', 'novembre', 'décembre'];
const List<String> _shortEn = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const List<String> _shortFr = ['janv.', 'févr.', 'mars', 'avr.', 'mai', 'juin', 'juil.', 'août', 'sept.', 'oct.', 'nov.', 'déc.'];

String monthName(int m) => (currentLanguage == AppLanguage.fr ? _monthsFr : _monthsEn)[m - 1];
String shortMonth(int m) => (currentLanguage == AppLanguage.fr ? _shortFr : _shortEn)[m - 1];

/// "Sep 3" in English, "3 sept." in French.
String monthDay(DateTime d) => currentLanguage == AppLanguage.fr ? '${d.day} ${shortMonth(d.month)}' : '${shortMonth(d.month)} ${d.day}';

